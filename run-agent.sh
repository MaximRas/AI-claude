#!/usr/bin/env bash
# Claude-агент для API-автотестов (GitLab CI или локально).
#
# AGENT_TASK:
#   mr-impact   — разбор MR сервиса: план проверки + тесты на новые/изменённые эндпоинты.
#                 Нужны: SERVICE_PROJECT_PATH, SERVICE_MR_IID, SERVICE_SOURCE_SHA, SERVICE_TARGET_BRANCH,
#                 [SERVICE_NAME] (имя спеки; по умолчанию — из main.py сервиса).
#                 Локально вместо клонирования: SERVICE_REPO_DIR=<путь к checkout> (база = SERVICE_TARGET_BRANCH).
#   cover       — дописать тесты на непокрытые эндпоинты. Нужен SERVICE_NAME (auth-manager|object-manager|layout-manager).
#   specs-sync  — скачать спеки со стенда, если изменились — обновить specs/ и тесты.
#
# Общие: ANTHROPIC_API_KEY (или CLAUDE_CODE_OAUTH_TOKEN / Bedrock / Vertex — см. docs/CI.md), GITLAB_API_TOKEN (scope api,
#   write_repository), CI_SERVER_HOST, CI_PROJECT_PATH, CI_PROJECT_ID, CI_API_V4_URL.
#   AGENT_DRY_RUN=true — ничего не пушить и не комментировать (проверка локально).
#   CLAUDE_MAX_TURNS (80), CLAUDE_MODEL (по умолчанию — модель CLI), TESTS_TARGET_BRANCH (master).
set -euo pipefail
cd "$(dirname "$0")"

AGENT_TASK="${AGENT_TASK:?AGENT_TASK не задан (mr-impact|cover|specs-sync)}"
CLAUDE_MAX_TURNS="${CLAUDE_MAX_TURNS:-80}"
TESTS_TARGET_BRANCH="${TESTS_TARGET_BRANCH:-master}"
AGENT_DRY_RUN="${AGENT_DRY_RUN:-false}"
REPORTS=reports
mkdir -p "${REPORTS}" logs
# локально (вне GitLab CI) хост GitLab берём из config/config.yaml
if [[ -z "${CI_SERVER_HOST:-}" ]]; then
  CI_SERVER_HOST="$(python -c 'from config.settings import get_settings as g; from urllib.parse import urlparse; print(urlparse(g().gitlab_host).netloc)')"
  export CI_SERVER_HOST
fi

log() { echo -e "\n=== $* ==="; }

require() {
  local missing=()
  for v in "$@"; do [[ -n "${!v:-}" ]] || missing+=("$v"); done
  if ((${#missing[@]})); then
    echo "ERROR: не заданы переменные: ${missing[*]}" >&2
    exit 2
  fi
}

if [[ "${AGENT_SKIP_AUTH_CHECK:-false}" != "true" && -z "${ANTHROPIC_API_KEY:-}" && -z "${CLAUDE_CODE_OAUTH_TOKEN:-}" \
  && -z "${CLAUDE_CODE_USE_BEDROCK:-}" && -z "${CLAUDE_CODE_USE_VERTEX:-}" ]]; then
  echo "ERROR: нужен ANTHROPIC_API_KEY | CLAUDE_CODE_OAUTH_TOKEN | CLAUDE_CODE_USE_BEDROCK | CLAUDE_CODE_USE_VERTEX" >&2
  exit 2
fi

git config --global user.name "${AGENT_GIT_NAME:-api-tests-agent}"
git config --global user.email "${AGENT_GIT_EMAIL:-api-tests-agent@metapix.ai}"
git config --global --add safe.directory "$(pwd)"

run_claude() {
  # $1 — prompt, $2 — имя отчёта
  local prompt="$1" name="$2"
  local model_args=()
  [[ -n "${CLAUDE_MODEL:-}" ]] && model_args=(--model "${CLAUDE_MODEL}")
  log "Claude: ${name}"
  set +e
  # Секреты GitLab/Allure/Slack в процесс агента не передаём: diff MR — недоверенный ввод (prompt injection).
  # Сеть наружу и push запрещены; всё, что уходит в GitLab, делает этот скрипт после агента.
  env -u GITLAB_API_TOKEN -u CI_JOB_TOKEN -u CI_REGISTRY_PASSWORD -u ALLURE_TOKEN -u SLACK_WEBHOOK_URL \
    claude -p "${prompt}" \
    "${model_args[@]}" \
    --permission-mode acceptEdits \
    --allowedTools "Read,Write,Edit,Grep,Glob,Task,Bash" \
    --disallowedTools "WebFetch,WebSearch,Bash(curl:*),Bash(wget:*),Bash(nc:*),Bash(ssh:*),Bash(scp:*),Bash(git push:*),Bash(git remote:*),Bash(pip install:*),Bash(npm:*),Bash(env:*),Bash(printenv:*)" \
    --max-turns "${CLAUDE_MAX_TURNS}" \
    --output-format json >"${REPORTS}/claude_${name}.json" 2>"logs/claude_${name}.err"
  local rc=$?
  set -e
  python - "${REPORTS}/claude_${name}.json" <<'PY' || true
import json, sys
try:
    d = json.load(open(sys.argv[1]))
    print(f"claude: turns={d.get('num_turns')} cost=${d.get('total_cost_usd', 0):.2f} "
          f"duration={int(d.get('duration_ms', 0)) // 1000}s is_error={d.get('is_error')}")
except Exception as exc:  # noqa: BLE001
    print(f"claude: нет json-отчёта ({exc})")
PY
  return ${rc}
}

# Изменил ли агент тесты/клиенты (то, что идёт в MR)
has_test_changes() {
  [[ -n "$(git status --porcelain -- services tests tools/coverage_ignore.yaml specs)" ]]
}

lint_agent_changes() {
  log "Проверка изменений агента"
  ruff check . --fix || true
  ruff format . || true
  python -m pytest -m selftest -q -p no:cacheprovider
  python -m pytest --collect-only -q -p no:cacheprovider >/dev/null
}

# Ветка + MR в репозитории автотестов. Печатает URL MR.
push_and_open_mr() {
  local branch="$1" title="$2" description_file="$3"
  if [[ "${AGENT_DRY_RUN}" == "true" ]]; then
    echo "DRY RUN: ветка ${branch} не пушится" >&2
    git --no-pager diff --stat >&2
    echo ""
    return 0
  fi
  require GITLAB_API_TOKEN CI_SERVER_HOST CI_PROJECT_PATH CI_PROJECT_ID
  git checkout -B "${branch}" >&2
  git add services tests tools/coverage_ignore.yaml specs
  git commit -q -m "${title}" -m "Generated by Claude agent (${AGENT_TASK}). Pipeline: ${CI_PIPELINE_URL:-local}" >&2
  git push -q -f "https://oauth2:${GITLAB_API_TOKEN}@${CI_SERVER_HOST}/${CI_PROJECT_PATH}.git" "HEAD:refs/heads/${branch}" >&2
  python ci/scripts/gitlab_mr.py open-mr --project "${CI_PROJECT_ID}" --source "${branch}" --target "${TESTS_TARGET_BRANCH}" \
    --title "${title}" --description-file "${description_file}"
}

# ---------------------------------------------------------------------------
task_mr_impact() {
  require SERVICE_PROJECT_PATH SERVICE_MR_IID SERVICE_SOURCE_SHA SERVICE_TARGET_BRANCH
  local svc_dir="service-src" service_slug base
  service_slug="$(basename "${SERVICE_PROJECT_PATH}")"

  if [[ -n "${SERVICE_REPO_DIR:-}" ]]; then
    svc_dir="${SERVICE_REPO_DIR}"
    base="${SERVICE_TARGET_BRANCH}"
    log "Локальный checkout ${svc_dir} (база ${base})"
  else
    log "Checkout ${SERVICE_PROJECT_PATH} @ ${SERVICE_SOURCE_SHA} (база ${SERVICE_TARGET_BRANCH})"
    rm -rf "${svc_dir}"
    local repo_url
    if [[ -n "${GITLAB_API_TOKEN:-}" ]]; then
      repo_url="https://oauth2:${GITLAB_API_TOKEN}@${CI_SERVER_HOST}/${SERVICE_PROJECT_PATH}.git"
    else
      repo_url="https://gitlab-ci-token:${CI_JOB_TOKEN}@${CI_SERVER_HOST}/${SERVICE_PROJECT_PATH}.git"
    fi
    git clone -q --filter=blob:none --no-checkout "${repo_url}" "${svc_dir}"
    git -C "${svc_dir}" fetch -q origin "${SERVICE_TARGET_BRANCH}" "${SERVICE_SOURCE_SHA}"
    git -C "${svc_dir}" checkout -q "${SERVICE_SOURCE_SHA}"
    base="origin/${SERVICE_TARGET_BRANCH}"
  fi

  log "Детерминированный анализ (tools.mr_impact)"
  local service_arg=()
  [[ -n "${SERVICE_NAME:-}" ]] && service_arg=(--service "${SERVICE_NAME}")
  python -m tools.mr_impact --repo "${svc_dir}" --base "${base}" "${service_arg[@]}" \
    --json "${REPORTS}/impact.json" --md "${REPORTS}/impact.md"

  local write_flag=""
  [[ "${AGENT_WRITE_TESTS:-true}" != "true" ]] && write_flag="--no-write"
  run_claude "/mr-tests ${svc_dir} ${base} ${write_flag}" "mr_impact" || echo "WARN: claude завершился с ошибкой"
  [[ -s "${REPORTS}/mr_comment.md" ]] || cp "${REPORTS}/impact.md" "${REPORTS}/mr_comment.md"
  [[ -s "${REPORTS}/agent_report.md" ]] || cp "${REPORTS}/mr_comment.md" "${REPORTS}/agent_report.md"

  local tests_mr=""
  if has_test_changes; then
    lint_agent_changes
    tests_mr="$(push_and_open_mr "autotests/${service_slug}-mr-${SERVICE_MR_IID}" \
      "autotests: ${service_slug} !${SERVICE_MR_IID}" "${REPORTS}/agent_report.md")"
  fi

  if [[ "${AGENT_DRY_RUN}" != "true" ]]; then
    require GITLAB_API_TOKEN
    local footer="_API tests agent · [pipeline](${CI_PIPELINE_URL:-#})_"
    [[ -n "${tests_mr}" ]] && footer="**MR с автотестами:** ${tests_mr}"$'\n\n'"${footer}"
    python ci/scripts/gitlab_mr.py note --project "${SERVICE_PROJECT_PATH}" --mr "${SERVICE_MR_IID}" \
      --file "${REPORTS}/mr_comment.md" --append "${footer}"
  else
    log "DRY RUN: комментарий в MR"; cat "${REPORTS}/mr_comment.md"
  fi
}

task_cover() {
  require SERVICE_NAME
  log "Покрытие ${SERVICE_NAME} до"
  python -m tools.coverage --service "${SERVICE_NAME}" --json "${REPORTS}/coverage_before.json" | head -3
  run_claude "/cover-endpoint ${SERVICE_NAME} --uncovered. В конце запиши reports/agent_report.md: какие тесты добавлены и что не покрыто." "cover" \
    || echo "WARN: claude завершился с ошибкой"
  if has_test_changes; then
    lint_agent_changes
    python -m tools.coverage --service "${SERVICE_NAME}" | head -3 | tee -a "${REPORTS}/agent_report.md"
    push_and_open_mr "autotests/cover-${SERVICE_NAME}-${CI_PIPELINE_ID:-local}" \
      "autotests: покрытие ${SERVICE_NAME}" "${REPORTS}/agent_report.md"
  else
    echo "Агент не внёс изменений"
  fi
}

task_specs_sync() {
  log "Скачивание спек со стенда ${TEST_ENV:-alphatest1}"
  python -m tools.fetch_specs | tee "${REPORTS}/specs_fetch.md"
  if [[ -z "$(git status --porcelain -- specs)" ]]; then
    echo "Спеки не изменились"
    return 0
  fi
  : >"${REPORTS}/spec_diff.md"
  for f in $(git status --porcelain -- specs | awk '{print $2}'); do
    { echo "## ${f}"; python -m tools.spec_diff "${f}" --git-ref HEAD; echo; } >>"${REPORTS}/spec_diff.md"
  done
  run_claude "Спеки в specs/ обновлены со стенда, diff — в reports/spec_diff.md. Используя субагента api-test-writer и skill api-autotest-writer: обнови клиенты и тесты под изменения контракта, добавь тесты на новые эндпоинты, удали тесты удалённых. Отчёт — reports/agent_report.md." "specs_sync" \
    || echo "WARN: claude завершился с ошибкой"
  lint_agent_changes
  cat "${REPORTS}/spec_diff.md" >>"${REPORTS}/agent_report.md" 2>/dev/null || cp "${REPORTS}/spec_diff.md" "${REPORTS}/agent_report.md"
  push_and_open_mr "autotests/specs-sync-$(date +%Y%m%d)" "specs: синхронизация со стендом ${TEST_ENV:-alphatest1}" "${REPORTS}/agent_report.md"
}

case "${AGENT_TASK}" in
  mr-impact) task_mr_impact ;;
  cover) task_cover ;;
  specs-sync) task_specs_sync ;;
  *) echo "ERROR: неизвестный AGENT_TASK=${AGENT_TASK}" >&2; exit 2 ;;
esac
